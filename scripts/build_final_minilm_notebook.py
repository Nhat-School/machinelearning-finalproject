def add(kind,source):
    item={'cell_type':kind,'id':hashlib.sha256(source.encode()).hexdigest()[:12],'metadata':{},'source':source.splitlines(keepends=True)}
    if kind=='code':item.update(execution_count=None,outputs=[])
    cells.append(item)
